// Only ephemeral test keys are generated; no production key is accessed.
func signedVersionFixture(t *testing.T, dir, version string) (string, string, asset) {
	t.Helper()
	pub, priv, err := minisign.GenerateKey(nil)
	if err != nil {
		t.Fatal(err)
	}
	public, err := pub.MarshalText()
	if err != nil {
		t.Fatal(err)
	}
	key := base64.StdEncoding.EncodeToString(public)
	name := "PassShare_0.1.0_x64-setup.exe"
	message := []byte("test-only update payload")
	comment := "timestamp:1\tfile:" + name
	if version != "" {
		comment += "\tversion:" + version
	}
	sig := base64.StdEncoding.EncodeToString(minisign.SignWithComments(priv, message, comment, "disposable test signature"))
	path := filepath.Join(dir, name)
	write(t, path, message)
	write(t, path+".sig", []byte(sig))
	a, err := updaterCheck(path, key)
	if err != nil {
		t.Fatal(err)
	}
	a.OSSignature = "authenticode_trusted_publisher_and_timestamp"
	a.EmbeddedVersion = "0.1.0"
	a.ApplicationSHA256 = strings.Repeat("b", 64)
	return key, sig, a
}

func TestSignedVersionManifestSuccessAndAuthenticatedComment(t *testing.T) {
	dir := scratch(t)
	key, _, a := signedVersionFixture(t, dir, "0.1.0")
	u := "https://github.com/" + repository + "/releases/download/v0.1.0/" + a.Name
	if err := writeVerifiedManifestWithKey(dir, source{TauriVersion: "0.1.0"}, u, a, key); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "latest.json")); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, a.Name)
	data, err := os.ReadFile(path + ".sig")
	if err != nil {
		t.Fatal(err)
	}
	decoded, err := base64.StdEncoding.DecodeString(string(data))
	if err != nil {
		t.Fatal(err)
	}
	changed := strings.Replace(string(decoded), "version:0.1.0", "version:0.2.0", 1)
	write(t, path+".sig", []byte(base64.StdEncoding.EncodeToString([]byte(changed))))
	if _, err := updaterCheckForVersion(path, key, "0.2.0"); err == nil {
		t.Fatal("unauthenticated comment mutation accepted")
	}
	for _, bad := range []string{"0.1.0\tversion:0.2.0", "0.1.0\tversion:0.1.0", "v0.1.0"} {
		d := scratch(t)
		k, _, a := signedVersionFixture(t, d, bad)
		if _, err := updaterCheckForVersion(filepath.Join(d, a.Name), k, "0.1.0"); err == nil {
			t.Fatal("noncanonical or ambiguous signed version accepted")
		}
	}
}

// Optional local acceptance of the lockfile-selected CLI; never uses real keys.
// CI exercises the deterministic crypto tests above without acquiring a new CLI.
func TestInstalledTauriSignerVersion(t *testing.T) {
	cli := os.Getenv("TEST_TAURI_CLI")
	if cli == "" {
		t.Skip("explicit installed CLI path is required for local acceptance")
	}
	dir := scratch(t)
	path := filepath.Join(dir, "PassShare_0.1.0_x64-setup.exe")
	write(t, path, []byte("test-only CLI signing"))
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	generate := exec.CommandContext(ctx, "node", cli, "signer", "generate", "--ci")
	generate.Env = cleanEnv(false)
	generate.Stdin = strings.NewReader("")
	var generated bytes.Buffer
	generate.Stdout = &generated
	generate.Stderr = io.Discard
	generate.WaitDelay = 3 * time.Second
	if generate.Run() != nil {
		t.Fatal("installed CLI could not generate disposable in-memory keys")
	}
	var key, private string
	lines := strings.Split(strings.ReplaceAll(generated.String(), "\r\n", "\n"), "\n")
	for i, line := range lines {
		if i+1 < len(lines) {
			switch strings.TrimSpace(line) {
			case "Private: (Keep it secret!)":
				private = strings.TrimSpace(lines[i+1])
			case "Public:":
				key = strings.TrimSpace(lines[i+1])
			}
		}
	}
	generated.Reset()
	if key == "" || private == "" {
		t.Fatal("CLI test key capture did not match fixed CLI format")
	}
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	// Use the same command builder and Windows PowerShell/pnpm path as production.
	c := updaterSigningCommand(ctx, root, "pnpm", path, "0.1.0")
	c.Env = append(cleanEnv(false), "TAURI_SIGNING_PRIVATE_KEY="+private, "TAURI_SIGNING_PRIVATE_KEY_PASSWORD=", "CANDIDATE_UPDATER="+path, "CANDIDATE_APP_VERSION=0.1.0")
	c.Stdin = strings.NewReader("")
	c.Stdout = io.Discard
	c.Stderr = io.Discard
	c.WaitDelay = 3 * time.Second
	if c.Run() != nil {
		t.Fatal("installed CLI did not sign disposable fixture")
	}
	if _, err := updaterCheckForVersion(path, key, "0.1.0"); err != nil {
		t.Fatal(err)
	}
	if _, err := updaterCheckForVersion(path, key, "0.2.0"); err == nil {
		t.Fatal("CLI signature accepted a different version")
	}
}
func TestManifestRejectsValidSignatureForDifferentOrMissingVersion(t *testing.T) {
	for _, version := range []string{"0.2.0", ""} {
		t.Run("signed_"+version, func(t *testing.T) {
			dir := scratch(t)
			key, _, a := signedVersionFixture(t, dir, version)
			u := "https://github.com/" + repository + "/releases/download/v0.1.0/" + a.Name
			if _, err := updaterCheckForVersion(filepath.Join(dir, a.Name), key, "0.1.0"); err == nil {
				t.Fatal("version check itself accepted a different or missing version")
			}
			if err := writeVerifiedManifestWithKey(dir, source{TauriVersion: "0.1.0"}, u, a, key); err == nil {
				t.Fatal("cryptographically valid signature without matching version accepted")
			}
			if _, err := os.Stat(filepath.Join(dir, "latest.json")); !os.IsNotExist(err) {
				t.Fatal("rejected version produced manifest")
			}
		})
	}
}
