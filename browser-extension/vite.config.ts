import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { resolve } from 'path';
import { copyFileSync, mkdirSync, existsSync, readdirSync } from 'fs';

// Plugin to copy assets and fix popup.html location
function copyAssetsPlugin() {
  return {
    name: 'copy-assets',
    closeBundle() {
      const distDir = resolve(__dirname, 'dist');
      const assetsDir = resolve(distDir, 'assets');

      // Create assets directory
      if (!existsSync(assetsDir)) {
        mkdirSync(assetsDir, { recursive: true });
      }

      // Copy manifest.json
      copyFileSync(
        resolve(__dirname, 'manifest.json'),
        resolve(distDir, 'manifest.json')
      );

      // Copy icons from project root if they exist
      const logoPath = resolve(__dirname, '..', 'logo.png');
      if (existsSync(logoPath)) {
        // Generate icons will be done by build script
        console.log('[CopyAssets] Logo found, icons should be generated by build script');
      }

      // Move popup HTML to correct location
      const popupSrcHtml = resolve(distDir, 'src', 'popup', 'index.html');
      const popupDestHtml = resolve(distDir, 'popup.html');
      if (existsSync(popupSrcHtml)) {
        // Read, fix paths, and write
        const fs = require('fs');
        let content = fs.readFileSync(popupSrcHtml, 'utf-8');
        // Fix asset paths
        content = content.replace(/src="\/popup\.js"/g, 'src="popup.js"');
        content = content.replace(/href="\/popup\.css"/g, 'href="popup.css"');
        content = content.replace(/src="\/src\/popup\/popup\.js"/g, 'src="popup.js"');
        content = content.replace(/href="\/src\/popup\/popup\.css"/g, 'href="popup.css"');
        fs.writeFileSync(popupDestHtml, content);
        console.log('[CopyAssets] Created popup.html with fixed paths');
      }

      console.log('[CopyAssets] Assets copied successfully');
    },
  };
}

export default defineConfig({
  plugins: [react(), copyAssetsPlugin()],
  build: {
    outDir: 'dist',
    rollupOptions: {
      input: {
        popup: resolve(__dirname, 'src/popup/index.html'),
        background: resolve(__dirname, 'src/background/index.ts'),
        content: resolve(__dirname, 'src/content/index.ts'),
      },
      output: {
        entryFileNames: '[name].js',
        chunkFileNames: '[name].js',
        assetFileNames: '[name].[ext]',
      },
    },
    emptyOutDir: true,
  },
});
